'use strict';

const SUPPORTED_PROVIDERS = new Set(['firebase', 'erpnext']);
const REQUIRED_ERPNEXT_ENV = [
  'FRAPPE_BASE_URL',
  'FRAPPE_API_KEY',
  'FRAPPE_API_SECRET',
  'ERPNEXT_COMPANY',
];

function clean(value, max = 240) {
  return String(value || '').trim().slice(0, max);
}

function financeProviderName(env = process.env) {
  const name = clean(env.FINANCE_PROVIDER || 'firebase', 40).toLowerCase();
  if (!SUPPORTED_PROVIDERS.has(name)) throw new Error(`Unsupported FINANCE_PROVIDER: ${name}`);
  return name;
}

function erpNextConfiguration(env = process.env) {
  const missing = REQUIRED_ERPNEXT_ENV.filter((key) => !clean(env[key], 1000));
  return { configured: missing.length === 0, missing };
}

function payerIdentity(studentId, student = {}) {
  const explicitId = clean(student.payerId || student.payerUid || student.companyId || student.companyRegCode, 160);
  const parentId = clean(student.linkedParentId || student.parentUid || student.guardianUid, 160);
  const id = explicitId || parentId || `student:${clean(studentId, 140)}`;
  const companyName = clean(student.companyName, 240);
  const parentName = clean(student.parentName || student.guardianName, 240);
  const name = clean(student.payerName || companyName || parentName || student.name, 240);
  if (!name) throw new Error('Payer name is missing for student');
  return {
    id,
    name,
    companyName,
    parentName,
    isCompany: Boolean(companyName || student.payerRegCode || student.companyRegCode),
    email: clean(student.payerEmail || student.parentEmail || student.guardianEmail || student.contactEmail || student.email, 180),
    regCode: clean(student.payerRegCode || student.companyRegCode, 80),
    address: clean(student.payerAddress || student.companyAddress || student.address, 500),
  };
}

function erpNextManualInvoiceView({ invoice, input, studentId, student, payer, actor, billingKey, requestId, nowIso }) {
  const amount = Number(invoice?.grandTotal || input.amount || 0);
  const outstanding = Number(invoice?.outstandingAmount ?? amount);
  return {
    id: invoice?.id || '',
    num: invoice?.id || '',
    externalInvoiceId: invoice?.id || '',
    backend: 'erpnext',
    status: outstanding <= 0 ? 'Makstud' : 'Ootel',
    erpNextStatus: invoice?.status || '',
    date: String(nowIso || '').slice(0, 10),
    due: invoice?.dueDate || input.due,
    studentId,
    studentName: clean(student?.name, 240) || '—',
    payerName: payer.name,
    payerEmail: payer.email,
    payerRegCode: payer.regCode,
    amount,
    amountCents: Math.round(amount * 100),
    paidAmount: Math.max(0, amount - outstanding),
    paidAmountCents: Math.round(Math.max(0, amount - outstanding) * 100),
    balanceDue: Math.max(0, outstanding),
    balanceDueCents: Math.round(Math.max(0, outstanding) * 100),
    paymentStatus: outstanding <= 0 ? 'paid' : 'unpaid',
    desc: input.description,
    note: input.note || '',
    billingMode: 'manual_charge_erpnext_v1',
    autoGenerated: false,
    billingKey,
    requestId,
    createdAt: nowIso,
    createdBy: actor,
  };
}

module.exports = {
  REQUIRED_ERPNEXT_ENV,
  erpNextConfiguration,
  erpNextManualInvoiceView,
  financeProviderName,
  payerIdentity,
};
