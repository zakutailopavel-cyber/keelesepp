function cleanText(value, maxLength = 500) {
  return String(value || '').trim().slice(0, maxLength);
}

function validIsoDate(value, field = 'date') {
  const clean = String(value || '').trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(clean)) throw new Error(`Valid ${field} required`);
  const parsed = new Date(`${clean}T12:00:00.000Z`);
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== clean) {
    throw new Error(`Valid ${field} required`);
  }
  return clean;
}

function toCents(value, field = 'amount') {
  const amount = Number(value);
  if (!Number.isFinite(amount) || amount <= 0) throw new Error(`Positive ${field} required`);
  const cents = Math.round(amount * 100);
  if (cents <= 0 || cents > 100000000) throw new Error(`Valid ${field} required`);
  return cents;
}

function manualInvoiceInput(values = {}) {
  const studentId = cleanText(values.studentId, 160);
  if (!studentId) throw new Error('studentId required');
  const description = cleanText(values.description, 300);
  if (!description) throw new Error('Description required');
  const amountCents = toCents(values.amount, 'amount');
  const due = validIsoDate(values.due, 'due date');
  return {
    studentId,
    description,
    amountCents,
    amount: amountCents / 100,
    due,
    note: cleanText(values.note, 500),
  };
}

