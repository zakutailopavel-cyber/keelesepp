    studentName: payer.studentName,
    subject: String(student.subject || '').trim().slice(0, 80),
    parentUid: payer.parentUid,
    linkedParentId: payer.linkedParentId,
    guardianUid: payer.guardianUid,
    parentName: payer.parentName,
    parentEmail: payer.parentEmail,
    parentEmailLower: payer.parentEmailLower,
    payerName: payer.payerName,
    payerEmail: payer.payerEmail,
    payerEmailLower: payer.payerEmailLower,
    amountCents: input.amountCents,
    amount: input.amount,
    paidAmountCents: 0,
    paidAmount: 0,
    balanceDueCents: input.amountCents,
    balanceDue: input.amount,
    overpaidAmountCents: 0,
    overpaidAmount: 0,
    paymentStatus: 'unpaid',
    paymentCount: 0,
    parentPaymentStatus: 'pending',
    parentPaymentMethod: '',
    parentPaymentSubmittedAt: '',
    emailStatus: '',
    emailRecipient: '',
    emailSentAt: '',
    emailLastType: '',
    lastReminderSentAt: '',
    reminderCount: 0,
    due10ReminderMonth: '',
    desc: input.description,
    note: input.note,
